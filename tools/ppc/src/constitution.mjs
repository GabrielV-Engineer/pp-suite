import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { loadProject } from './load.mjs';
import { designFindings, validateModel } from './validate.mjs';
import { modeOf, testPolicy } from './policy.mjs';

// Spec Kit reads a "constitution" and checks every plan against its principles. Here it is not written by hand: it is
// produced from the design, by a script, so the rules the planner is held to are the rules of `.architect/`. It is the
// same text every time (no date), and its version is the blueprint revision.

export const CONSTITUTION_FILE = '.specify/memory/constitution.md';
export class ConstitutionError extends Error {}
const fail = (message) => {
  throw new ConstitutionError(message);
};

const MARK = '<!-- Generated by ppc from .architect/blueprint.yaml';
const bullets = (items) => items.map((i) => `- ${i}`);

export function renderConstitution(model) {
  const bp = model.blueprint.data;
  const mode = modeOf(bp, {});
  const policy = testPolicy(bp, {});
  const adrs = model.adrs.filter((a) => a.data.status === 'accepted').sort((a, b) => a.data.id.localeCompare(b.data.id));
  const lines = [
    `${MARK} (revision ${bp.revision}). Do not edit this file: change the design through a change request, then run \`ppc constitution\`. -->`,
    `# ${bp.project.name} Constitution`,
    '',
    '## Core Principles',
    '',
    '### I. The design is decided; planning does not re-decide it',
    'The stack, the components and the decisions come from `.architect/`. A specification, plan or task list MUST use only the components below and MUST NOT introduce another framework, storage or tool.',
    ...(adrs.length ? ['Decisions in force:', ...bullets(adrs.map((a) => `${a.data.id} ${a.data.title}`))] : []),
    'If the design is wrong or silent about something the work needs, stop and open a change request (`ppc change-request`). Do not choose for yourself.',
    '',
    '### II. Non-goals are never built (NON-NEGOTIABLE)',
    'The project does not do any of the following. Specifications, plans, tasks and code MUST NOT include them, not even as a convenience:',
    ...bullets(bp.non_goals),
    '',
    '### III. Components keep their boundaries',
    ...bullets(bp.components.map((c) => `**${c.id}** (${c.kind}): ${c.responsibility} ${c.may_depend_on.length ? `May depend only on: ${c.may_depend_on.join(', ')}.` : 'May depend on nothing.'}`)),
    '',
    '### IV. Quality targets are measurable',
    ...bullets(bp.quality_attributes.map((q) => `${q.id} (${q.attribute}): ${q.scenario} Metric: ${q.metric}. Target: ${q.target}.`)),
    'Work that can affect a target MUST say how it is verified against its metric.',
    '',
    '### V. Work in thin vertical slices',
    `Plan by observable behavior, never by layer. The first slice is a deployable skeleton. The hand-written production code of a slice stays under ${bp.budgets.max_slice_production_lines} lines; a bigger slice MUST be split. Every slice states what it leaves out of scope.`,
    '',
    '### VI. Tests follow the policy',
    `Default cycle: ${mode === 'light' ? 'the light cycle (tests and code together in one session)' : 'the strict cycle (failing tests first, approved by a person, then code with the tests locked)'}; a slice may choose the other. Test policy: ${policy} (${{ required: 'a slice cannot close without tests', optional: 'a slice may close without tests, and a debt entry is proposed', none: 'tests are not asked for' }[policy]}).`,
    'Tests are never weakened, deleted or skipped to get a green result.',
    '',
    '### VII. People decide',
    'Approving a slice or its tests, accepting or paying technical debt, an exception to a budget, keeping an addition to the design and accepting a change request are decisions for a person. An agent proposes them and never records them.',
    '',
    '## Governance',
    '',
    'This constitution is derived from the design and changes only when the design does. Where it conflicts with a plan, the constitution wins.',
    '',
    `**Version**: blueprint revision ${bp.revision}`,
    '',
  ];
  return lines.join('\n');
}

function loadValid(root) {
  const model = loadProject(root);
  // Only the design is judged: this runs before any slice exists, when rules about slices have nothing to see.
  const errors = designFindings(validateModel(model)).filter((f) => f.severity === 'error');
  if (!model.blueprint || errors.length) fail(`the design is not valid, fix it first:\n${errors.slice(0, 5).map((e) => `  ${e.rule} ${e.file}: ${e.message}`).join('\n')}`);
  return model;
}

/** Writes the constitution. Replaces Spec Kit's empty template and this tool's earlier output, never a hand-written file. */
export function writeConstitution(root, { force = false } = {}) {
  const model = loadValid(root);
  const pending = (model.additions?.data.additions ?? []).filter((a) => a.decision === 'pending').map((a) => a.id);
  if (pending.length && !force) fail(`these additions are undecided: ${pending.join(', ')}. Decide them first (ppc decide-addition), or the constitution would hold the plan to things you may cut. --force writes it anyway`);
  const out = renderConstitution(model);
  const abs = join(root, CONSTITUTION_FILE);
  if (existsSync(abs)) {
    const current = readFileSync(abs, 'utf8');
    if (current === out) return { file: CONSTITUTION_FILE, status: 'unchanged' };
    const ours = current.startsWith(MARK) || /\[PROJECT_NAME\]|\[PRINCIPLE_1_NAME\]/.test(current);
    if (!ours && !force) fail(`${CONSTITUTION_FILE} looks hand-written; it will not be replaced without --force`);
  }
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, out);
  return { file: CONSTITUTION_FILE, status: 'written' };
}

/** Problems with the constitution on disk, as messages; empty when it matches the design. */
export function checkConstitution(root) {
  const abs = join(root, CONSTITUTION_FILE);
  if (!existsSync(abs)) return [`${CONSTITUTION_FILE} is missing; run \`ppc constitution\``];
  return readFileSync(abs, 'utf8') === renderConstitution(loadValid(root)) ? [] : [`${CONSTITUTION_FILE} is out of date with the design; run \`ppc constitution\``];
}
