import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';

const HEADER = '<!-- GENERATED by `ppc generate`. Do not edit: change the source files instead. -->';
const cell = (value) => String(value ?? '—').replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');
const row = (cells) => `| ${cells.map(cell).join(' | ')} |`;
const table = (head, rows) => [row(head), row(head.map(() => '---')), ...rows.map(row)].join('\n');

function renderWbs(model) {
  const bp = model.blueprint.data;
  const slices = model.slices.map((s) => s.data).sort((a, b) => a.id.localeCompare(b.id));
  const count = (status) => slices.filter((s) => s.status === status).length;
  const head = ['Slice', 'Title', 'Type', 'Status', 'Components', 'Depends on'];
  const line = (s) => [s.id, s.title, s.type, s.status, s.components.join(', '), (s.depends_on ?? []).join(', ') || '—'];
  const sections = bp.capabilities.map((cap) => {
    const own = slices.filter((s) => s.capability === cap.id);
    return `## ${cap.id} — ${cap.name} (${cap.priority})\n\n${own.length ? table(head, own.map(line)) : '_No slices yet._'}`;
  });
  const loose = slices.filter((s) => !s.capability);
  if (loose.length) sections.push(`## Cross-cutting\n\n${table(head, loose.map(line))}`);
  const summary = ['planned', 'ready', 'in_progress', 'done', 'dropped'].map((st) => `${st.replace('_', ' ')} ${count(st)}`).join(' · ');
  return [
    HEADER,
    `# Work breakdown — ${bp.project.name}`,
    `Blueprint revision ${bp.revision} · ${slices.length} slices · ${summary}`,
    ...sections,
  ].join('\n\n') + '\n';
}

function renderDebt(component, entries) {
  const head = ['ID', 'Title', 'Kind', 'Origin', 'Cost of delay', 'Trigger', 'Status', 'Paid by'];
  const rows = entries.map((e) => [e.id, e.title, e.kind, `${e.origin.type}: ${e.origin.ref}`, e.cost_of_delay.level, e.trigger, e.status, e.paid_by]);
  return [
    HEADER,
    `# Technical debt — ${component.name} (${component.code})`,
    rows.length ? table(head, rows) : '_No entries._',
  ].join('\n\n') + '\n';
}

/** Returns Map(relative path → content) of every derived view. */
export function generate(model) {
  const out = new Map();
  out.set('.sddpp/wbs.md', renderWbs(model));
  for (const c of model.blueprint.data.components) {
    const entries = model.debt.find((d) => d.data?.component === c.id)?.data.entries ?? [];
    out.set(`.sddpp/debt/${c.id}.md`, renderDebt(c, entries));
  }
  return out;
}

export function writeGenerated(root, views) {
  for (const [file, content] of views) {
    mkdirSync(dirname(join(root, file)), { recursive: true });
    writeFileSync(join(root, file), content);
  }
}

export function checkGenerated(root, views) {
  const findings = [];
  for (const [file, content] of views) {
    const abs = join(root, file);
    if (!existsSync(abs)) findings.push({ rule: 'G01', severity: 'error', file, message: 'generated view is missing; run `ppc generate`' });
    else if (readFileSync(abs, 'utf8') !== content) findings.push({ rule: 'G01', severity: 'error', file, message: 'generated view is stale; run `ppc generate`' });
  }
  return findings;
}
